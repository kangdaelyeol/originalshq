export const DEMO_LAST_FRAME = DEMO_FIRST_FRAME + DEMO_SHAPES.length - 1

const SEGMENTS = ROPE_POINTS - 1

/** 모양 한 줄([고정점 x, 길이, 각 K개]) → 점 17개(x, y 번갈아) */
export function buildDemoShape(row: readonly number[], out: Float32Array = new Float32Array(ROPE_POINTS * 2)) {
  const ax = row[0]
  const len = row[1] / SEGMENTS
  const k = row.length - 2
  out[0] = ax
  out[1] = ROPE_BASE_Y
  for (let i = 0; i < SEGMENTS; i++) {
    // 마디 사이 각은 Catmull-Rom으로 — 영상에서 맞출 때와 같은 식
    const t = ((i + 0.5) / SEGMENTS) * (k - 1)
    const j = Math.min(k - 2, Math.floor(t))
    const u = t - j
    const p0 = row[2 + Math.max(0, j - 1)]
    const p1 = row[2 + j]
    const p2 = row[2 + j + 1]
    const p3 = row[2 + Math.min(k - 1, j + 2)]
    const a =
      0.5 * (2 * p1 + (-p0 + p2) * u + (2 * p0 - 5 * p1 + 4 * p2 - p3) * u * u + (-p0 + 3 * p1 - 3 * p2 + p3) * u * u * u)
    out[(i + 1) * 2] = out[i * 2] + len * Math.cos(a)
    out[(i + 1) * 2 + 1] = out[i * 2 + 1] + len * Math.sin(a)
  }
  return out
}

const rowAt = (frame: number) => {
  const f = Math.min(Math.max(frame - DEMO_FIRST_FRAME, 0), DEMO_SHAPES.length - 1)
  const i = Math.floor(f)
  const t = f - i
  const a = DEMO_SHAPES[i]
  const b = DEMO_SHAPES[Math.min(i + 1, DEMO_SHAPES.length - 1)]
  return a.map((v, k) => v + (b[k] - v) * t)
}

/** 영상 프레임(소수 가능) → 그 순간 젤리 모양(점 17개). 프레임 사이는 모양 값을 이어 섞는다. */
export const demoShapeAt = (frame: number, out?: Float32Array) => buildDemoShape(rowAt(frame), out)

/** 프레임마다 손잡이(줄 마지막 점) x — 모양에서 뽑는다 */
export const DEMO_KNOB_PATH: readonly number[] = DEMO_SHAPES.map((row) => buildDemoShape(row)[SEGMENTS * 2])

/** 영상 프레임(소수 가능) → 손잡이 x */
export const demoKnobAt = (frame: number) => demoShapeAt(frame)[SEGMENTS * 2]

/** 영상 프레임 → 그 프레임에 보이던 바닥 숫자 */
export const demoPercentAt = (frame: number) =>
  DEMO_PERCENT[Math.min(Math.max(Math.floor(frame + 1e-6) - DEMO_FIRST_FRAME, 0), DEMO_PERCENT.length - 1)]
